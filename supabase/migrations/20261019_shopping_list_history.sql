-- Restock: keep every finished shopping list, and record taxes per trip.
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run.

-- 1. One row per item per finished trip. `shopping_list` stays the current list.
create table if not exists public.shopping_list_history (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  -- Links to shopping_history.shopping_id (one trip can cover several stores).
  shopping_id    text not null,
  -- Kept even if the item is later deleted; name/store/price are snapshots.
  item_id        bigint references public.item_list (id) on delete set null,
  item_name      text not null,
  shopping_place text,
  amount         integer not null default 1,
  price          numeric,
  -- Checked off in the shopping list during the trip.
  bought         boolean not null default false,
  -- Added to inventory at Finish Trip (true for bought items, and for
  -- unchecked items the shopper confirmed in the review window).
  added_to_stock boolean not null default false
);

create index if not exists shopping_list_history_shopping_id_idx
  on public.shopping_list_history (shopping_id);

-- Signed-in users can read and write; the public key on its own cannot.
alter table public.shopping_list_history enable row level security;

drop policy if exists "Signed-in users manage shopping list history" on public.shopping_list_history;
create policy "Signed-in users manage shopping list history"
  on public.shopping_list_history
  for all
  to authenticated
  using (true)
  with check (true);

-- 2. Tax amounts entered when editing a trip.
alter table public.shopping_history
  add column if not exists gst numeric,
  add column if not exists hst numeric;
